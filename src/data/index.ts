export const findCountry = (id: string) => countries.find((c) => c.id === id);
export const findCity = (id: string | undefined) => cities.find((c) => c.id === id);
export const findCategory = (id: string | undefined) => categories.find((c) => c.id === id);
export const findTrip = (id: string) => trips.find((t) => t.id === id);
export const findHotel = (id: string) => hotels.find((h) => h.id === id);
export const findVisa = (id: string) => visas.find((v) => v.id === id);
export const findDestination = (id: string | undefined) => destinations.find((d) => d.id === id);

export function countryName(id: string): string {
  return findCountry(id)?.name ?? "Unknown";
}
export function cityName(id?: string): string {
  return id ? findCity(id)?.name ?? "—" : "—";
}
